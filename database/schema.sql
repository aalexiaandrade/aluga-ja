create table if not exists usuarios (
  id bigint generated by default as identity primary key,
  nome varchar(120) not null,
  email varchar(160) not null unique,
  senha varchar(255) not null,
  tipo varchar(20) not null check (tipo in ('CLIENTE','AGENTE')),
  criado_em timestamp not null default now()
);

create table if not exists clientes (
  id bigint generated by default as identity primary key,
  usuario_id bigint not null unique references usuarios(id) on delete cascade,
  rg varchar(30),
  cpf varchar(14) unique,
  endereco varchar(220),
  profissao varchar(100)
);

create table if not exists rendimentos (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references clientes(id) on delete cascade,
  empregador varchar(140) not null,
  valor numeric(12,2) not null check (valor > 0)
);

create table if not exists veiculos (
  id bigint generated by default as identity primary key,
  matricula varchar(30) not null,
  ano integer not null,
  marca varchar(70) not null,
  modelo varchar(70) not null,
  placa varchar(10) not null unique,
  proprietario varchar(20) not null check (proprietario in ('CLIENTE','EMPRESA','BANCO'))
);

create table if not exists pedidos_aluguel (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references clientes(id),
  veiculo_id bigint not null references veiculos(id),
  data_inicio date not null,
  data_fim date not null,
  valor_total numeric(12,2) not null,
  possui_credito boolean default false,
  banco_agente varchar(140),
  valor_credito numeric(12,2),
  status varchar(20) not null default 'PENDENTE',
  parecer_agente varchar(1000),
  agente_id bigint references usuarios(id),
  criado_em timestamp not null default now(),
  atualizado_em timestamp default now()
);

create index if not exists idx_pedidos_cliente on pedidos_aluguel(cliente_id);
create index if not exists idx_pedidos_status on pedidos_aluguel(status);

